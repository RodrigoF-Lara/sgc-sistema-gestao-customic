-- Padroniza o kardex vivo.
-- KARDEX_2026_EMBALAGEM passa a se chamar KARDEX_LOTE (estoque por lote).
-- KARDEX_2026 passa a se chamar KARDEX_MOVIMENTO (entrada e saída).
-- Visões com os nomes antigos mantêm o site funcionando até o código ser trocado.
-- O ano continua na coluna KARDEX. ANO_VIVO começa em 2026.

EXEC sp_rename 'dbo.KARDEX_2026_EMBALAGEM', 'KARDEX_LOTE';
GO
EXEC sp_rename 'dbo.KARDEX_2026', 'KARDEX_MOVIMENTO';
GO

CREATE VIEW dbo.KARDEX_2026_EMBALAGEM AS
SELECT * FROM dbo.KARDEX_LOTE;
GO

CREATE VIEW dbo.KARDEX_2026 AS
SELECT * FROM dbo.KARDEX_MOVIMENTO;
GO

IF OBJECT_ID(N'dbo.TB_KARDEX_ANO', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_KARDEX_ANO (
        ID INT NOT NULL CONSTRAINT PK_TB_KARDEX_ANO PRIMARY KEY,
        ANO_VIVO INT NOT NULL,
        DT_VIRADA DATETIME NULL,
        USUARIO_VIRADA NVARCHAR(100) NULL
    );
    INSERT INTO dbo.TB_KARDEX_ANO (ID, ANO_VIVO) VALUES (1, 2026);
END
GO

IF NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE name = 'IX_KARDEX_LOTE_ANO_CODIGO' AND object_id = OBJECT_ID(N'dbo.KARDEX_LOTE')
)
    CREATE INDEX IX_KARDEX_LOTE_ANO_CODIGO ON dbo.KARDEX_LOTE (KARDEX, CODIGO);
GO

IF NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE name = 'IX_KARDEX_MOVIMENTO_ANO_CODIGO_DT' AND object_id = OBJECT_ID(N'dbo.KARDEX_MOVIMENTO')
)
    CREATE INDEX IX_KARDEX_MOVIMENTO_ANO_CODIGO_DT ON dbo.KARDEX_MOVIMENTO (KARDEX, CODIGO, DT);
GO
